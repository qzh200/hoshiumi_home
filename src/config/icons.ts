/** 校验图标名是否合法，并返回小写标准化结果 */
function normalizeIconName(raw: string): string {
  const match = /^[a-z0-9-]+$/.exec(raw);
  if (!match) {
    throw new Error(`[icons] 非法的图标名："${raw}"，图标名只能包含小写字母、数字与连字符。`);
  }
  return raw;
}

/** 用内置品牌图标构造一个 fill 风格 SVG（svg 尺寸交给 CSS） */
function wrapFallbackSvg(d: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="currentColor"><path d="${d}"/></svg>`;
}

/**
 * 读取 lucide 图标的原始 SVG 字符串（已剥离固定尺寸，便于 CSS 控制大小）。
 * @param spec 形如 `lucide:book-open`；品牌名（github 等）缺失时使用内置兜底
 */
export function loadLucideIconSvg(spec: string): string {
  const cached = cache.get(spec);
  if (cached) return cached;

  const prefix = 'lucide:';
  if (!spec.startsWith(prefix)) {
    throw new Error(`[icons] 不支持的图标前缀："${spec}"。当前仅支持 lucide 图标，格式为 lucide:图标名。`);
  }

  const name = normalizeIconName(spec.slice(prefix.length));
  const root = resolveLucideStaticRoot();
  const file = join(root, 'icons', `${name}.svg`);

  if (existsSync(file)) {
    const raw = readFileSync(file, 'utf8');
    // 去掉固定 width/height，让图标尺寸完全交给 CSS 控制
    const cleaned = raw
      .replace(/\s(width|height)="\d+"/g, '')
      .replace(/\n\s*/g, ' ');
    cache.set(spec, cleaned);
    return cleaned;
  }

  // Lucide 已移除的品牌图标 → 内置兜底
  const fallback = BRAND_FALLBACKS[name];
  if (fallback) {
    const svg = wrapFallbackSvg(fallback);
    cache.set(spec, svg);
    return svg;
  }

  throw new Error(
    `[icons] 找不到图标 lucide:${name}：在 lucide-static/icons/ 下不存在 ${name}.svg。` +
      `\n        请检查 config/site.yaml 中 links[].icon / social[].icon 的拼写，` +
      `或前往 https://lucide.dev/icons 查找可用图标名。` +
      `\n        （内置品牌兜底：github / x / telegram / bilibili / wechat）`
  );
}
